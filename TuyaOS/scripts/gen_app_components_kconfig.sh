#!/bin/bash
# Bootstrap app-level Kconfig inputs for an app.
#
# Run from the SDK root (the directory of the Makefile that invokes this):
#   bash scripts/gen_app_components_kconfig.sh <app_build_dir>
#
# Produces up to four files in <app_build_dir>/ (all bootstrap files use
# create-if-missing semantics; only auto_components_kconfig is regenerated
# on every run):
#
#   1. auto_components_kconfig       (always rewritten)
#      One `rsource "<rel>"` line per IoTOSconfig found under
#      application_components/ and application_drivers/.
#   2. APPconfig                     (created if missing)
#      Minimal Kconfig entry: mainmenu + `orsource "auto_components_kconfig"`
#      + comment placeholders for app-private items.
#   3. tuya_app_config-h-head        (created if missing)
#      C-header guard prefix used by config.mk's app_config target.
#   4. tuya_app_config-h-tail        (created if missing)
#      Matching suffix (extern "C" close + #endif).

set -eu

APP_BUILD_DIR="${1:-}"
if [ -z "${APP_BUILD_DIR}" ]; then
    echo "Usage: $0 <app_build_dir>" >&2
    exit 1
fi

mkdir -p "${APP_BUILD_DIR}"
APP_BUILD_DIR="$(cd "${APP_BUILD_DIR}" && pwd)"
SDK_ROOT="$(pwd)"

OUT_AUTO="${APP_BUILD_DIR}/auto_components_kconfig"
OUT_APPCONFIG="${APP_BUILD_DIR}/APPconfig"
OUT_HEAD="${APP_BUILD_DIR}/tuya_app_config-h-head"
OUT_TAIL="${APP_BUILD_DIR}/tuya_app_config-h-tail"

# ---------------------------------------------------------------------------
# 1) Scan application_components/ + application_drivers/ for IoTOSconfig.
#    -L so symlinked component dirs are followed.
# ---------------------------------------------------------------------------
SCAN_DIRS=()
for d in application_components application_drivers; do
    [ -d "${SDK_ROOT}/${d}" ] && SCAN_DIRS+=("${d}")
done

if [ "${#SCAN_DIRS[@]}" -eq 0 ]; then
    FOUND=""
else
    FOUND="$(find -L "${SCAN_DIRS[@]}" -type f -name IoTOSconfig -print0 2>/dev/null \
             | sort -z | tr '\0' '\n')"
fi

relpath() {
    python3 -c 'import os,sys; print(os.path.relpath(sys.argv[1], sys.argv[2]))' "$1" "${APP_BUILD_DIR}"
}

{
    echo "# -----------------------------------------------------------------------------"
    echo "# Auto-generated by scripts/gen_app_components_kconfig.sh — DO NOT EDIT."
    echo "# Regenerate via: make gen_app_kconfig APP_NAME=<name>"
    echo "# -----------------------------------------------------------------------------"

    if [ -z "${FOUND}" ]; then
        echo "# No application_components/application_drivers IoTOSconfig files found."
    else
        while IFS= read -r cfg; do
            [ -z "${cfg}" ] && continue
            rel="$(relpath "${SDK_ROOT}/${cfg}")"
            echo "rsource \"${rel}\""
        done <<< "${FOUND}"
    fi
} > "${OUT_AUTO}"
echo "[gen_app_components_kconfig] wrote ${OUT_AUTO}"

# ---------------------------------------------------------------------------
# 2) Bootstrap APPconfig (do NOT overwrite if the user already has one).
# ---------------------------------------------------------------------------
if [ ! -f "${OUT_APPCONFIG}" ]; then
    cat > "${OUT_APPCONFIG}" <<'EOF'
mainmenu "Tuya App Configuration"

# Auto-include application_components/ and application_drivers/ IoTOSconfig.
# Silently no-ops until auto_components_kconfig has real rsource lines.
orsource "auto_components_kconfig"

# App-private IoTOSconfig — uncomment and adjust the relative path:
# rsource "../src/<component>/IoTOSconfig"

# Add app-specific menuconfig items below, e.g.:
# config ENABLE_FOO
#     bool "Enable foo"
#     default n
EOF
    echo "[gen_app_components_kconfig] bootstrapped ${OUT_APPCONFIG}"
else
    echo "[gen_app_components_kconfig] ${OUT_APPCONFIG} exists, skip"
fi

# ---------------------------------------------------------------------------
# 3) Bootstrap C-header skeleton consumed by config.mk:app_config.
#    Matching the style of scripts/tuya_iot_config-h-head + tail.
# ---------------------------------------------------------------------------
if [ ! -f "${OUT_HEAD}" ]; then
    cat > "${OUT_HEAD}" <<'EOF'
/*
 * tuya_app_config.h — AUTO-GENERATED from APPconfig + tuya_app.config.
 * Do not edit by hand; rerun `make app_config_auto APP_NAME=<name>`.
 */
#ifndef TUYA_APP_CONFIG_H
#define TUYA_APP_CONFIG_H

#ifdef __cplusplus
extern "C" {
#endif

EOF
    echo "[gen_app_components_kconfig] bootstrapped ${OUT_HEAD}"
else
    echo "[gen_app_components_kconfig] ${OUT_HEAD} exists, skip"
fi

if [ ! -f "${OUT_TAIL}" ]; then
    cat > "${OUT_TAIL}" <<'EOF'

#ifdef __cplusplus
}
#endif

#endif /* TUYA_APP_CONFIG_H */
EOF
    echo "[gen_app_components_kconfig] bootstrapped ${OUT_TAIL}"
else
    echo "[gen_app_components_kconfig] ${OUT_TAIL} exists, skip"
fi
